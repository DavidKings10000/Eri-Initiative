import Image, { type ImageProps } from 'next/image';
import placeholders from '@/lib/image-placeholders.json';

const blurPreviews = placeholders as Record<string, string>;

type SiteImageProps = Omit<ImageProps, 'width' | 'height' | 'alt'> & {
  alt: string;
  width?: number;
  height?: number;
};

/**
 * Drop-in replacement for <img> that routes local photos through the Next.js
 * image optimizer (resized, converted to AVIF/WebP, lazy-loaded).
 *
 * Display size is still controlled by className (e.g. "h-52 w-full object-cover");
 * width/height only set the intrinsic aspect ratio, and `sizes` tells the browser
 * which resized variant to download.
 *
 * Photos get an instant blurred preview (generated by `npm run images`) while the
 * full image streams in. Small logos (width <= 128) skip it, since a blurred logo
 * looks like a smudge. Remote URLs (e.g. Unsplash) are already sized by their
 * query string, so they are served as-is instead of being proxied.
 */
export function SiteImage({
  src,
  width = 1600,
  height = 1067,
  sizes = '(min-width: 1024px) 50vw, 100vw',
  alt,
  ...props
}: SiteImageProps) {
  const isRemote = typeof src === 'string' && /^https?:\/\//.test(src);
  // next/image rejects bare paths like "photo.jpg"; treat them as files in /public.
  const resolvedSrc = typeof src === 'string' && !isRemote && !src.startsWith('/') ? `/${src}` : src;
  const blurDataURL = typeof resolvedSrc === 'string' && width > 128 ? blurPreviews[resolvedSrc] : undefined;

  return (
    <Image
      src={resolvedSrc}
      alt={alt}
      width={width}
      height={height}
      sizes={sizes}
      unoptimized={isRemote}
      {...(blurDataURL ? { placeholder: 'blur' as const, blurDataURL } : {})}
      {...props}
    />
  );
}
